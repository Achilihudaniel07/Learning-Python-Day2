# LIST COMMON METHODS

# sort() - arranges elements in ascending order
numbers = [50, 20, 40, 10]

numbers.sort()
print(numbers)

numbers.sort(reverse=False)
print(numbers)


# sort() - arranges elements in descending order
numbers = [30, 20, 40, 10, 60, 70]

numbers.sort(reverse=True) 
print(numbers)



# reverse() - reverses the current order (no sorting)
numbers = [10,20,30,50,40,25]

numbers.reverse() 
print(numbers)
